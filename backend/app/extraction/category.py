# 关键词→品目 倒排缓存
_INVERTED: dict[str, str] = {}
for _cat, _kws in _CATEGORY_RULES:
    for _k in _kws:
        _INVERTED.setdefault(_k, _cat)


def category_keywords() -> list[str]:
    """暴露关键词列表(供 LLM 提示词等复用)。"""
    return list(_INVERTED.keys())


def infer_category(product_name: str) -> str:
    """按产品服务名称推断品目; 未命中返回空串。"""
    if not product_name:
        return ""
    name = product_name.strip().replace(" ", "").replace("\u3000", "")
    if not name:
        return ""
    for cat, kws in _CATEGORY_RULES:
        for k in kws:
            if k in name:
                return cat
    return ""
